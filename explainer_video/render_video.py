def prepare_audio():
    global CAPTIONS
    count=int(DURATION*SR)
    speech=np.zeros(count,dtype=np.float32)
    duck=np.ones(count,dtype=np.float32)
    CAPTIONS=[]
    timings=[]
    ffmpeg=ffmpeg_exe()
    for i,cue in enumerate(TIMELINE["cues"]):
        data=read_wave(BASE/"audio"/f"{i:02}.wav")
        loud=np.flatnonzero(np.abs(data)>.004)
        if not len(loud):
            raise ValueError(f"Silent voice clip {i}")
        trim_start=max(0,loud[0]-int(.06*SR))
        data=data[trim_start:min(len(data),loud[-1]+int(.12*SR))]
        word_times=json.loads((BASE/"audio"/f"{i:02}.json").read_text(encoding="utf-8-sig"))
        if isinstance(word_times,dict):
            word_times=[word_times]
        assert word_times, f"No speech timing events for {i}"
        slot=cue["end"]-cue["start"]-.08
        original_duration=len(data)/SR
        tempo=max(1,original_duration/slot)
        if tempo>1:
            result=subprocess.run([ffmpeg,"-hide_banner","-loglevel","error","-f","f32le","-ar",str(SR),"-ac","1","-i","pipe:0","-af",f"atempo={tempo:.6f}","-f","f32le","pipe:1"],input=data.astype(np.float32).tobytes(),capture_output=True,check=True)
            data=np.frombuffer(result.stdout,dtype=np.float32).copy()
        if len(data)>round(slot*SR):
            data=data[:round(slot*SR)]
        data*=.79/(np.max(np.abs(data))+1e-9)
        start=round(cue["start"]*SR)
        speech[start:start+len(data)]+=data
        actual_end=cue["start"]+len(data)/SR
        duck[max(0,start-int(.08*SR)):min(count,start+len(data)+int(.22*SR))]=.24
        chunks=split_caption(cue["text"])
        starts=[]
        char_cursor=0
        for text in chunks:
            pos=cue["text"].find(text,char_cursor)
            assert pos>=0, (text,cue)
            char_cursor=pos+len(text)
            event=next(w for w in word_times if w["Position"]>=pos)
            relative=max(0,event["Seconds"]-trim_start/SR)/tempo
            starts.append(cue["start"]+relative)
        for j,text in enumerate(chunks):
            end=starts[j+1] if j+1<len(starts) else actual_end
            assert cue["start"]<=starts[j]<end<=actual_end+.003, (i,text,starts[j],end,actual_end)
            CAPTIONS.append({"start":round(starts[j],3),"end":round(end,3),"speaker":cue["speaker"],"text":text})
        timings.append({"cue":i,"speaker":cue["speaker"],"start":cue["start"],"end":round(actual_end,3),"original_seconds":round(original_duration,3),"tempo":round(tempo,3)})
    # Original restrained nightclub bed. All notes and percussion are synthesized.
    music=np.zeros(count,dtype=np.float32)
    beat=60/104
    rng=np.random.default_rng(46)
    chords=[[130.81,155.56,196.0],[103.83,130.81,155.56],[116.54,146.83,174.61],[98,123.47,146.83]]
    for b in range(math.ceil(DURATION/beat)):
        now=b*beat
        if 159.8<now<217.8:
            continue
        start=int(now*SR)
        if start>=count:
            continue
        kt=np.arange(int(.19*SR))/SR
        kick=np.sin(2*np.pi*(43*kt+4*(1-np.exp(-kt*22))))*np.exp(-kt*23)*.043
        n=min(len(kick),count-start)
        music[start:start+n]+=kick[:n]
        ht=np.arange(int(.055*SR))/SR
        hat=rng.normal(0,1,len(ht))*np.exp(-ht*85)*.006
        start2=start+int(beat*.5*SR)
        if start2<count:
            n=min(len(hat),count-start2)
            music[start2:start2+n]+=hat[:n]
        if b%2==0:
            nt=np.arange(int(beat*1.8*SR))/SR
            freqs=chords[(b//8)%4]
            notes=sum(np.sin(2*np.pi*f*nt)+.20*np.sin(4*np.pi*f*nt) for f in freqs)
            notes=notes*np.minimum(nt*80,1)*np.exp(-nt*2.5)*.006
            n=min(len(notes),count-start)
            music[start:start+n]+=notes[:n]
    # Silence is deliberate: the stopping-rule question arrives without a beat.
    music[int(159.8*SR):int(217.8*SR)]=0
    for sec,frequency in [(68.8,622.25),(83.7,830.61),(96,523.25),(96.25,659.25),(96.5,783.99),(138.2,196)]:
        st=int(sec*SR)
        nt=np.arange(int(.35*SR))/SR
        chime=np.sin(2*np.pi*frequency*nt)*np.exp(-nt*10)*.038
        music[st:st+len(chime)]+=chime
    # Music begins and ends smoothly, and sits below the words.
    fade=min(int(1.2*SR),count)
    music[:fade]*=np.linspace(0,1,fade)
    music[-fade:]*=np.linspace(1,0,fade)
    music*=duck
    stereo=np.column_stack([music+speech,music*.96+speech])
    peak=float(np.max(np.abs(stereo)))
    if peak>.94:
        stereo*=.94/peak
    write_wave(OUT/"master_audio.wav",stereo)
    write_wave(OUT/"voiceover.wav",speech)
    (OUT/"captions.json").write_text(json.dumps(CAPTIONS,indent=2),encoding="utf-8")
    (OUT/"voice_timings.json").write_text(json.dumps(timings,indent=2),encoding="utf-8")
    srt=[]
    vtt=["WEBVTT","", "NOTE Captions are also burned into the supplied MP4.", ""]
    for i,cap in enumerate(CAPTIONS):
        body="\n".join(textwrap.wrap(cap["text"],64,break_long_words=False,break_on_hyphens=False))
        speaker=cap["speaker"].upper()+": "
        srt.extend([str(i+1),f"{subtitle_time(cap['start'],True)} --> {subtitle_time(cap['end'],True)}",speaker+body,""])
        vtt.extend([f"{subtitle_time(cap['start'])} --> {subtitle_time(cap['end'])}",speaker+body,""])
    (OUT/"club_eligibility.srt").write_text("\n".join(srt),encoding="utf-8")
    (OUT/"club_eligibility.vtt").write_text("\n".join(vtt),encoding="utf-8")
    max_tempo=max(t["tempo"] for t in timings)
    print(f"Audio ready: {len(TIMELINE['cues'])} voice clips, {len(CAPTIONS)} captions; maximum timing adjustment {max_tempo:.3f}x.",flush=True)


