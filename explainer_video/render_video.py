def font(size, style="normal"):
    key = (round(size * SCALE), style)
    if key not in FONTS:
        FONTS[key] = ImageFont.truetype(str(FONTROOT / FONTFILES[style]), key[0])
    return FONTS[key]


def clamp(x, lo=0, hi=1):
    return min(hi, max(lo, x))


def smooth(x):
    x = clamp(x)
    return x * x * (3 - 2 * x)


def wrap_words(text, size, width, style="normal"):
    result, line = [], ""
    for word in text.split():
        candidate = f"{line} {word}".strip()
        if font(size, style).getlength(candidate) > width * SCALE and line:
            result.append(line)
            line = word
        else:
            line = candidate
    if line:
        result.append(line)
    return result


class Canvas:
    def __init__(self, im):
        self.im = im
        self.d = ImageDraw.Draw(im)

    def box(self, xy, fill, outline=None, radius=0, width=1):
        q = tuple(round(v * SCALE) for v in xy)
        if radius:
            self.d.rounded_rectangle(q, radius=round(radius * SCALE), fill=fill, outline=outline, width=max(1, round(width * SCALE)))
        else:
            self.d.rectangle(q, fill=fill, outline=outline, width=max(1, round(width * SCALE)))

    def line(self, points, fill, width=1):
        self.d.line([(round(x * SCALE), round(y * SCALE)) for x, y in points], fill=fill, width=max(1, round(width * SCALE)), joint="curve")

    def poly(self, points, fill, outline=None):
        self.d.polygon([(round(x * SCALE), round(y * SCALE)) for x, y in points], fill=fill, outline=outline)

    def ellipse(self, xy, fill, outline=None, width=1):
        self.d.ellipse(tuple(round(v * SCALE) for v in xy), fill=fill, outline=outline, width=max(1, round(width * SCALE)))

    def txt(self, xy, text, size=24, fill=WHITE, style="normal", anchor="lt", maxwidth=None):
        if maxwidth:
            while font(size, style).getlength(text) > maxwidth * SCALE and size > 10:
                size -= 0.5
        self.d.text(tuple(round(v * SCALE) for v in xy), text, font=font(size, style), fill=fill, anchor=anchor)

    def paragraph(self, xy, text, size=24, fill=MUTED, width=500, style="normal", leading=1.28):
        lines = wrap_words(text, size, width, style)
        for i, line in enumerate(lines):
            self.txt((xy[0], xy[1] + i * size * leading), line, size, fill, style)
        return len(lines) * size * leading

    def pill(self, x, y, text, color=TEAL, size=15, width=None):
        width = width or font(size, "bold").getlength(text) / SCALE + 28
        self.box((x, y, x + width, y + size + 17), PANEL, color, 8)
        self.txt((x + 14, y + 7), text, size, color, "bold")

    def arrow(self, a, b, color=TEAL, width=3):
        self.line([a, b], color, width)
        angle = math.atan2(b[1] - a[1], b[0] - a[0])
        self.poly([b, (b[0] - 11 * math.cos(angle - 0.5), b[1] - 11 * math.sin(angle - 0.5)), (b[0] - 11 * math.cos(angle + 0.5), b[1] - 11 * math.sin(angle + 0.5))], color)


def make_background():
    y, x = np.mgrid[0:HEIGHT, 0:WIDTH]
    a = np.exp(-((x - WIDTH * .75) ** 2 / (WIDTH * .52) ** 2 + (y - HEIGHT * .32) ** 2 / (HEIGHT * .48) ** 2))
    b = np.exp(-((x - WIDTH * .13) ** 2 / (WIDTH * .40) ** 2 + (y - HEIGHT * .65) ** 2 / (HEIGHT * .42) ** 2))
    rgb = np.zeros((HEIGHT, WIDTH, 3), dtype=np.uint8)
    for i, (base, av, bv) in enumerate([(7, 13, 5), (11, 5, 13), (25, 23, 15)]):
        rgb[:, :, i] = base + a * av + b * bv
    im = Image.fromarray(rgb)
    c = Canvas(im)
    c.box((0, 565, 1280, 720), "#0b1020")
    for i in range(-7, 16):
        c.line([(640 + i * 76, 565), (640 + i * 150, 720)], "#19233a")
    for y0 in [577, 602, 638, 688]:
        c.line([(0, y0), (1280, y0)], "#19233a")
    for x0 in [55, 420, 930, 1230]:
        c.line([(x0, 0), (x0, 565)], "#182039")
    return im


