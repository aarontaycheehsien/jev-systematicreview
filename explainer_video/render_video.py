def ffmpeg_exe():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def read_wave(path):
    with wave.open(str(path)) as f:
        assert f.getsampwidth()==2
        data=np.frombuffer(f.readframes(f.getnframes()),dtype=np.int16).astype(np.float32)/32768
        if f.getnchannels()>1:
            data=data.reshape(-1,f.getnchannels()).mean(axis=1)
        rate=f.getframerate()
        if rate!=SR:
            points=np.arange(round(len(data)*SR/rate),dtype=np.float64)*rate/SR
            data=np.interp(points,np.arange(len(data)),data).astype(np.float32)
    return data


def write_wave(path,data):
    data=np.clip(data,-1,1)
    with wave.open(str(path),"wb") as f:
        f.setnchannels(2 if data.ndim==2 else 1)
        f.setsampwidth(2)
        f.setframerate(SR)
        f.writeframes((data*32767).astype(np.int16).tobytes())


def split_caption(text,limit=86):
    # Sentence-aware: a punchline is not revealed a caption early.
    sentences=re.split(r"(?<=[.!?])\s+",text)
    chunks=[]
    for sentence in sentences:
        if len(sentence)<=limit:
            chunks.append(sentence)
        else:
            chunks.extend(textwrap.wrap(sentence,limit,break_long_words=False,break_on_hyphens=False))
    return chunks


def subtitle_time(t,srt=False):
    ms=round(t*1000)
    hh,ms=divmod(ms,3600000)
    mm,ms=divmod(ms,60000)
    ss,ms=divmod(ms,1000)
    return f"{hh:02}:{mm:02}:{ss:02}{',' if srt else '.'}{ms:03}"


